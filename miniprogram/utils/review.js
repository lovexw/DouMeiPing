// 记录每个「行业:风格」上一次的生成结果，避免连续生成重复文案
const lastText = {};

function pick(arr) {
  return arr[Math.floor(Math.random() * arr.length)];
}

function assemble(lib) {
  return [
    pick(lib.openers),
    pick(lib.cores),
    pick(lib.experiences),
    pick(lib.closers)
  ].join('。');
}

function industryLabel(industry) {
  const meta = INDUSTRIES[industry];
  return meta ? meta.label : INDUSTRIES.generic.label;
}

function generateReview(industry, style) {
  const key = industry + ':' + style;
  const lib = (LIBS[industry] || LIBS.generic)[style === 'xhs' ? 'xhs' : 'normal'];
  let text = '';
  // 最多重试 8 次，尽量不与上一条雷同
  for (let i = 0; i < 8; i++) {
    text = assemble(lib);
    if (text !== lastText[key]) break;
  }
  lastText[key] = text;
  return text;
}

module.exports = {
  INDUSTRIES,
  LIBS,
  industryLabel,
  generateReview
};
